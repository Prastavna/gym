// Generates src/data/exercises.dataset.ts from the hasaneyldrm/exercises-dataset.
//
// Usage:
//   node scripts/build-exercises.mjs [path-to-exercises.json]
//
// With no argument it downloads the dataset from GitHub; pass a local path to
// build offline. The dataset (1324 exercises) is trimmed to the fields this app
// needs — English instructions, equipment, derived difficulty and raw media
// URLs — and normalised so each exercise carries the muscle id it trains.
//
// Source: https://github.com/hasaneyldrm/exercises-dataset (© Gym Visual)

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const REPO = "hasaneyldrm/exercises-dataset";
const BRANCH = "main";
const RAW_BASE = `https://raw.githubusercontent.com/${REPO}/${BRANCH}`;
const DATASET_URL = `${RAW_BASE}/data/exercises.json`;

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_FILE = resolve(__dirname, "../src/data/exercises.dataset.ts");

/** Dataset `target` (primary trained muscle) → our muscle id in muscles.ts. */
const TARGET_TO_MUSCLE = {
  abs: "abdominals",
  pectorals: "pectorals",
  biceps: "biceps",
  glutes: "glutes",
  delts: "deltoids",
  triceps: "triceps",
  "upper back": "rhomboids",
  lats: "latissimus",
  calves: "calves",
  quads: "quadriceps",
  forearms: "forearms",
  hamstrings: "hamstrings",
  spine: "erector-spinae",
  traps: "trapezius",
  adductors: "adductors",
  "serratus anterior": "serratus",
  abductors: "glutes", // hip abductors = gluteus medius/minimus
  "levator scapulae": "neck",
  "cardiovascular system": null, // no discrete muscle — dropped
};

/** Equipment → difficulty heuristic (the dataset ships no difficulty rating). */
const EQUIPMENT_DIFFICULTY = {
  "body weight": "beginner",
  assisted: "beginner",
  band: "beginner",
  "resistance band": "beginner",
  "stability ball": "beginner",
  "bosu ball": "beginner",
  "medicine ball": "beginner",
  roller: "beginner",
  "wheel roller": "beginner",
  rope: "beginner",
  "elliptical machine": "beginner",
  "stationary bike": "beginner",
  "upper body ergometer": "beginner",
  "skierg machine": "beginner",
  "stepmill machine": "beginner",
  dumbbell: "intermediate",
  cable: "intermediate",
  kettlebell: "intermediate",
  "leverage machine": "intermediate",
  "smith machine": "intermediate",
  "sled machine": "intermediate",
  hammer: "intermediate",
  barbell: "advanced",
  "ez barbell": "advanced",
  "olympic barbell": "advanced",
  "trap bar": "advanced",
  weighted: "advanced",
  tire: "advanced",
};

const difficultyFor = (equipment) => EQUIPMENT_DIFFICULTY[equipment] ?? "intermediate";

async function loadDataset(arg) {
  if (arg) {
    return JSON.parse(await readFile(arg, "utf8"));
  }
  const res = await fetch(DATASET_URL);
  if (!res.ok) throw new Error(`Failed to download dataset: ${res.status}`);
  return res.json();
}

function normalise(raw) {
  const out = [];
  for (const ex of raw) {
    const muscleId = TARGET_TO_MUSCLE[ex.target];
    if (muscleId === undefined) {
      throw new Error(`Unmapped target "${ex.target}" (exercise ${ex.id})`);
    }
    if (muscleId === null) continue; // cardio etc.

    const steps = ex.instruction_steps?.en ?? [];
    const description = ex.instructions?.en ?? steps.join(" ");

    out.push({
      id: ex.id,
      name: ex.name,
      muscleId,
      target: ex.target,
      muscleGroup: ex.muscle_group ?? null,
      secondaryMuscles: ex.secondary_muscles ?? [],
      equipment: ex.equipment ?? null,
      difficulty: difficultyFor(ex.equipment),
      description,
      steps,
      image: ex.image ? `${RAW_BASE}/${ex.image}` : null,
      gif: ex.gif_url ? `${RAW_BASE}/${ex.gif_url}` : null,
    });
  }
  return out;
}

function render(records) {
  const header = `// AUTO-GENERATED by scripts/build-exercises.mjs — do not edit by hand.
// Source: https://github.com/${REPO} (© Gym Visual — https://gymvisual.com/)
// Regenerate with: node scripts/build-exercises.mjs [path-to-exercises.json]

export interface DatasetExercise {
  id: string;
  name: string;
  /** Primary muscle id this exercise trains (matches muscles.ts ids). */
  muscleId: string;
  /** Raw dataset target label. */
  target: string;
  muscleGroup: string | null;
  secondaryMuscles: string[];
  equipment: string | null;
  difficulty: "beginner" | "intermediate" | "advanced";
  description: string;
  steps: string[];
  image: string | null;
  gif: string | null;
}

export const datasetExercises: DatasetExercise[] = `;

  return `${header}${JSON.stringify(records, null, 2)};\n`;
}

const raw = await loadDataset(process.argv[2]);
const records = normalise(raw);
await writeFile(OUT_FILE, render(records), "utf8");
console.log(`Wrote ${records.length} exercises to ${OUT_FILE}`);
